    /**
     * tests the constructor and the getter
     *
     * @param array{factory: string|null, search: list<string>|null} $version
     *
     * @throws ExpectationFailedException
     */
    #[DataProvider(methodName: 'provider')]
    public function testType(
        string $type,
        string | null $name,
        string | null $marketingName,
        Company $company,
        array $version,
        string $key,
    ): void {
        $result = Os::tryFrom($type);

        if ($result === null) {
            self::fail(sprintf('unknown OS %s', $type));
        }

        self::assertSame($name, $result->getName());
        self::assertSame($marketingName, $result->getMarketingName());
        self::assertSame($company, $result->getManufacturer());
        self::assertSame($version, $result->getVersion());
        self::assertSame($key, $result->getKey());

        if (
            $name !== null
            && !in_array(
                $name,
                ['Windows', 'Windows NT', 'Windows RT', 'Windows Phone OS'],
                strict: true,
            )
        ) {
            $result2 = Os::fromName($name);

            self::assertSame($name, $result2->getName());
            self::assertSame($marketingName, $result2->getMarketingName());
            self::assertSame($company, $result2->getManufacturer());
            self::assertSame($version, $result2->getVersion());
            self::assertSame($key, $result2->getKey());
        }

        $os = Os::fromName($key);

        self::assertSame($name, $os->getName());
        self::assertSame($marketingName, $os->getMarketingName());
        self::assertSame($company, $os->getManufacturer());
        self::assertSame($version, $os->getVersion());
        self::assertSame($key, $os->getKey());

        $result4 = Os::fromName($result->value);

        self::assertSame($name, $result4->getName());
        self::assertSame($marketingName, $result4->getMarketingName());
        self::assertSame($company, $result4->getManufacturer());
        self::assertSame($version, $result4->getVersion());
        self::assertSame($key, $result4->getKey());

        $result5 = Os::fromName($result->name);

        self::assertSame($name, $result5->getName());
        self::assertSame($marketingName, $result5->getMarketingName());
        self::assertSame($company, $result5->getManufacturer());
        self::assertSame($version, $result5->getVersion());
        self::assertSame($key, $result5->getKey());
    }

